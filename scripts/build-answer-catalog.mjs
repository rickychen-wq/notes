import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root=path.resolve(import.meta.dirname,'..');
const outputPath=path.join(root,'answer-catalog.js');

function arrayLiteral(source,name){
  const match=new RegExp(String.raw`(?:const|let|var)\s+${name}\s*=\s*`).exec(source);
  if(!match)throw new Error(`Missing ${name} data`);
  const start=source.indexOf('[',match.index+match[0].length);if(start<0)throw new Error(`Missing ${name} array`);
  let depth=0,quote='',escaped=false,lineComment=false,blockComment=false;
  for(let i=start;i<source.length;i++){
    const char=source[i],next=source[i+1];
    if(lineComment){if(char==='\n')lineComment=false;continue;}
    if(blockComment){if(char==='*'&&next==='/'){blockComment=false;i++;}continue;}
    if(quote){if(escaped){escaped=false;continue;}if(char==='\\'){escaped=true;continue;}if(char===quote)quote='';continue;}
    if(char==='/'&&next==='/'){lineComment=true;i++;continue;}
    if(char==='/'&&next==='*'){blockComment=true;i++;continue;}
    if(char==='\''||char==='"'||char==='`'){quote=char;continue;}
    if(char==='[')depth++;
    if(char===']'&&--depth===0)return source.slice(start,i+1);
  }
  throw new Error(`Unclosed ${name} array`);
}

function readArray(file,name){
  const source=fs.readFileSync(path.join(root,file),'utf8');
  return vm.runInNewContext(`(${arrayLiteral(source,name)})`,Object.create(null),{timeout:1000});
}

function plain(value){return String(value??'').replace(/<[^>]*>/g,'').replace(/\s+/g,' ').trim();}
function addDetail(catalog,pageId,key,detail){
  const normalized=plain(key);if(!normalized)return;
  catalog[pageId]??={};catalog[pageId][normalized]??=detail;
}

const meanings={},details={};
const englishPages=['en-book-l1.html','en-book-l2.html','en-4500-9-1.html','en-4500-9-2.html','en-4500-10.html','en-mag-4-6.html','en-mag-7-9.html','en-mag-10-14.html'];
for(const file of englishPages){
  const pageId=path.basename(file,'.html');
  for(const row of readArray(file,'WORDS')){
    const shifted=typeof row[1]==='number';
    const term=plain(row[shifted?2:1]),pos=plain(row[4]),zh=plain(row[5]);
    const meaning=plain([pos,zh].filter(Boolean).join(' '));
    if(/^[A-Za-z]+(?:['-][A-Za-z]+)*$/.test(term))meanings[term.toLocaleLowerCase('en')]??=meaning;
    addDetail(details,pageId,term,{question:meaning||term,correctAnswer:term});
  }
  for(const row of readArray(file,'PHRASES')){
    const shifted=typeof row[0]==='string'&&/^\w+\d+$/i.test(row[0]);
    const term=plain(row[shifted?1:0]),meaning=plain(row[shifted?2:1]);
    addDetail(details,pageId,term,{question:meaning||term,correctAnswer:term});
  }
}

for(const item of readArray('en-mag-1-3.html','BANK')){
  const term=plain(item.en),meaning=plain(item.zh);
  if(item.k==='word'&&/^[A-Za-z]+(?:['-][A-Za-z]+)*$/.test(term))meanings[term.toLocaleLowerCase('en')]??=meaning;
  addDetail(details,'en-mag-1-3',term,{question:meaning||term,correctAnswer:term});
}

for(const file of ['bio-photo.html','ch-reading.html','math-1.html']){
  const pageId=path.basename(file,'.html');
  for(const row of readArray(file,'RAW'))addDetail(details,pageId,row[1],{question:plain(row[1]),correctAnswer:plain(row[2])});
}

for(const row of readArray('chem-1.html','RAW')){
  const question=plain(`${row[0]} ${row[1]}`),detail={question,correctAnswer:plain(row[2])};
  addDetail(details,'chem-1',row[0],detail);addDetail(details,'chem-1',question,detail);
}

for(const item of readArray('chem-2.html','BANK')){
  addDetail(details,'chem-2',item.q,{question:plain(item.q),correctAnswer:plain(item.c?.[item.a])});
}

const glyphRows=['R1','R2','R3'].flatMap(function(name){return readArray('ch-glyph.html',name);});
for(const row of glyphRows){
  const answer=plain(row[1]),question=plain(row[0]).replace(/（[^）]*）/g,answer);
  addDetail(details,'ch-glyph',answer,{question,correctAnswer:answer});
}

function sortedObject(value){
  return Object.fromEntries(Object.entries(value).sort(function(a,b){return a[0].localeCompare(b[0]);}).map(function(entry){
    return[entry[0],entry[1]&&typeof entry[1]==='object'&&!Array.isArray(entry[1])?sortedObject(entry[1]):entry[1]];
  }));
}

const generated=`// Generated by scripts/build-answer-catalog.mjs. Do not edit by hand.\n`+
  `export const ENGLISH_MEANINGS=${JSON.stringify(sortedObject(meanings),null,2)};\n\n`+
  `export const LEGACY_WRONG_DETAILS=${JSON.stringify(sortedObject(details),null,2)};\n`;

if(process.argv.includes('--check')){
  if(!fs.existsSync(outputPath)||fs.readFileSync(outputPath,'utf8')!==generated){
    console.error('answer-catalog.js is missing or out of date. Run npm run build:catalog.');process.exit(1);
  }
}else{
  fs.writeFileSync(outputPath,generated,'utf8');
  console.log(`Wrote answer-catalog.js with ${Object.keys(meanings).length} English meanings and ${Object.values(details).reduce((sum,page)=>sum+Object.keys(page).length,0)} legacy answers.`);
}
