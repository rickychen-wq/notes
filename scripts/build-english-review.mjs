import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root=path.resolve(import.meta.dirname,'..');
const outputPath=path.join(root,'english-review-data.js');

const pages=[
  {file:'en-book-l1.html',group:'book',label:'課本 Lesson 1'},
  {file:'en-book-l2.html',group:'book',label:'課本 Lesson 2'},
  {file:'en-book-l3.html',group:'book',label:'課本 Lesson 3'},
  {file:'en-mag-1-3.html',group:'mag',label:'雜誌 U1–U3',bank:true},
  {file:'en-mag-4-6.html',group:'mag',label:'雜誌 U4–U6'},
  {file:'en-mag-7-9.html',group:'mag',label:'雜誌 U7–U9'},
  {file:'en-mag-10-14.html',group:'mag',label:'雜誌 U10–U14'},
  {file:'en-4500-9-1.html',group:'vocab',label:'4500 單 9-1'},
  {file:'en-4500-9-2.html',group:'vocab',label:'4500 單 9-2'},
  {file:'en-4500-10.html',group:'vocab',label:'4500 單 10'},
  {file:'en-4500-11-1.html',group:'vocab',label:'4500 單 11-1'},
  {file:'en-4500-11-2.html',group:'vocab',label:'4500 單 11-2'}
];

function arrayLiteral(source,name){
  const match=new RegExp(String.raw`(?:const|let|var)\s+${name}\s*=\s*`).exec(source);
  if(!match)throw new Error(`Missing ${name} data`);
  const start=source.indexOf('[',match.index+match[0].length);if(start<0)throw new Error(`Missing ${name} array`);
  let depth=0,quote='',escaped=false,lineComment=false,blockComment=false;
  for(let i=start;i<source.length;i++){
    const char=source[i],next=source[i+1];
    if(lineComment){if(char==='\n')lineComment=false;continue;}
    if(blockComment){if(char==='*'&&next==='/'){blockComment=false;i++;}continue;}
    if(quote){if(escaped){escaped=false;continue;}if(char==='\\'){escaped=true;continue;}if(char===quote)quote='';continue;}
    if(char==='/'&&next==='/'){lineComment=true;i++;continue;}
    if(char==='/'&&next==='*'){blockComment=true;i++;continue;}
    if(char==='\''||char==='"'||char==='`'){quote=char;continue;}
    if(char==='[')depth++;
    if(char===']'&&--depth===0)return source.slice(start,i+1);
  }
  throw new Error(`Unclosed ${name} array`);
}

function readArray(source,name){
  return vm.runInNewContext(`(${arrayLiteral(source,name)})`,Object.create(null),{timeout:1000});
}

function plain(value){return String(value??'').replace(/<[^>]*>/g,'').replace(/\s+/g,' ').trim();}
function distractors(value){
  if(Array.isArray(value))return value.map(plain).filter(Boolean);
  const raw=plain(value);if(!raw)return[];
  return raw.includes('|')?raw.split('|').map(plain).filter(Boolean):raw.split(/\s+/).map(plain).filter(Boolean);
}

const items=[];
for(const page of pages){
  const source=fs.readFileSync(path.join(root,page.file),'utf8');
  if(page.bank){
    for(const item of readArray(source,'BANK'))items.push({
      k:item.k==='phrase'?'phrase':'word',en:plain(item.en),zh:plain(item.zh),pos:plain(item.pos),
      note:plain(item.note),d:distractors(item.d),alt:(item.alt||[]).map(plain).filter(Boolean),
      source:page.group,lesson:page.label,pageId:path.basename(page.file,'.html')
    });
    continue;
  }
  for(const row of readArray(source,'WORDS')){
    const shifted=typeof row[1]==='number';
    items.push({k:'word',en:plain(row[shifted?2:1]),zh:plain(row[5]),pos:plain(row[4]),note:plain(row[6]),
      d:distractors(row[7]),alt:[],source:page.group,lesson:page.label,pageId:path.basename(page.file,'.html')});
  }
  for(const row of readArray(source,'PHRASES')){
    const shifted=typeof row[0]==='string'&&/^\w+\d+$/i.test(row[0]);
    items.push({k:'phrase',en:plain(row[shifted?1:0]),zh:plain(row[shifted?2:1]),pos:'片語',
      note:plain(row[shifted?3:2]),d:distractors(row[shifted?4:3]),alt:[],source:page.group,
      lesson:page.label,pageId:path.basename(page.file,'.html')});
  }
}

const cleanItems=items.filter(function(item){return item.en&&item.zh;});
const generated=`// Generated by scripts/build-english-review.mjs. Do not edit by hand.\n`+
  `export const ENGLISH_REVIEW_ITEMS=${JSON.stringify(cleanItems,null,2)};\n`+
  `export const ENGLISH_REVIEW_SOURCES=${JSON.stringify(pages.map(function(page){return page.file;}))};\n`;

if(process.argv.includes('--check')){
  if(!fs.existsSync(outputPath)||fs.readFileSync(outputPath,'utf8')!==generated){
    console.error('english-review-data.js is missing or out of date. Run npm run build:review.');process.exit(1);
  }
}else{
  fs.writeFileSync(outputPath,generated,'utf8');
  const words=cleanItems.filter(function(item){return item.k==='word';}).length;
  const phrases=cleanItems.length-words;
  console.log(`Wrote english-review-data.js with ${words} words and ${phrases} phrases from ${pages.length} pages.`);
}
